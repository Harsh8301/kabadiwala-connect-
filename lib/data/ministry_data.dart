String mt(String language, String key) =>
    ministryText[language]?[key] ?? ministryText['en']?[key] ?? key;

List<String> safetyLines(String language, String materialId) => [
      mt(language, '${materialId}WarningBody'),
      mt(language, '${materialId}WarningSteps'),
    ];

String statusLabel(LotStatus value, [String language = 'en']) {
  final localized = mt(language, 'status_${value.name}');
  if (localized != 'status_${value.name}') {
    return localized;
  }
  return value.name
      .replaceAllMapped(RegExp(r'([A-Z])'), (match) => ' ${match.group(1)}')
      .trim();
}
